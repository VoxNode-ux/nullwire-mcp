// Command trigramgen trains the trigram table used by the borderline
// escalation in internal/app/tokenscore.go.
//
// It counts byte triples inside identifier-like tokens of a benign corpus
// (real source and docs plus diverse synthetic identifiers) and a secret
// corpus (synthetic hex, base62 and base64url, plus an optional file of real
// secrets), and keeps the triples with the strongest
// log2(P(triple|benign) / P(triple|secret)). Polarity matches bigramgen and
// tokenscore.go: positive = benign, negative = secret.
//
// Each entry is one uint32: (a<<14|b<<7|c)<<8 | (score - lo), so the table is
// sorted by key and the runtime binary-searches it without allocating. The
// output file is data only.
//
// Usage (see the go:generate line in internal/app/tokenscore.go):
//
//	go run ./tools/trigramgen -benign dir1,file2 [-secrets file] [-synthetic N] [-synthetic-benign N] [-holdout-mod N] -out trigram_trained.go
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"math"
	"os"
	"sort"
	"strings"

	"github.com/VoxNode-ux/nullwire-mcp/internal/cliio"
	"github.com/VoxNode-ux/nullwire-mcp/tools/internal/corpus"
)

const (
	lo, hi     = -4, 6 // same evidence range as bigramgen / bigramMean
	minCount   = 30    // a triple needs this many observations (both classes)
	minAbs     = 2     // weaker evidence is pruned
	maxEntries = 16384 // <= 64 KiB of uint32
	maxBytes   = 64 << 10
)

type counts []uint32 // indexed by a<<14|b<<7|c

func newCounts() counts { return make(counts, 128*128*128) }

func addToken(c counts, tok string) {
	for i := 2; i < len(tok); i++ {
		if a, b, d := tok[i-2], tok[i-1], tok[i]; a < 128 && b < 128 && d < 128 {
			c[int(a)<<14|int(b)<<7|int(d)]++
		}
	}
}

func addText(c counts, text string) int {
	return corpus.Tokens(text, func(tok string) { addToken(c, tok) })
}

type entry struct {
	key   uint32 // a<<14|b<<7|c
	score int
	count float64
}

// pack returns the table word for one entry: key<<8 | (score-lo).
func pack(key uint32, score int) uint32 {
	d := score - lo // 0..10 for a clamped score; kept inside the 8-bit field regardless
	if d < 0 {
		d = 0
	} else if d > 255 {
		d = 255
	}
	return key<<8 | uint32(d)
}

// train turns the two count tables into the pruned, size-capped entry list.
func train(benign, secret counts) []entry {
	var tb, ts float64
	seen := 0
	for i := range benign {
		tb += float64(benign[i])
		ts += float64(secret[i])
		if benign[i]+secret[i] > 0 {
			seen++
		}
	}
	if tb == 0 || ts == 0 {
		return nil
	}
	const alpha = 0.5 // additive smoothing over the observed triples
	denomB := tb + alpha*float64(seen)
	denomS := ts + alpha*float64(seen)
	var out []entry
	var key uint32 // index of benign[i], counted alongside the loop
	for i := range benign {
		k := key
		key++
		n := benign[i] + secret[i]
		if n < minCount {
			continue
		}
		v := math.Round(math.Log2(((float64(benign[i]) + alpha) / denomB) / ((float64(secret[i]) + alpha) / denomS)))
		v = math.Max(lo, math.Min(hi, v))
		if math.Abs(v) < minAbs {
			continue
		}
		out = append(out, entry{k, int(v), float64(n)})
	}
	// Keep the top-magnitude entries; ties by evidence, then key, so the
	// result is deterministic.
	sort.Slice(out, func(i, j int) bool {
		ai, aj := abs(out[i].score), abs(out[j].score)
		if ai != aj {
			return ai > aj
		}
		if out[i].count != out[j].count {
			return out[i].count > out[j].count
		}
		return out[i].key < out[j].key
	})
	if len(out) > maxEntries {
		out = out[:maxEntries]
	}
	sort.Slice(out, func(i, j int) bool { return out[i].key < out[j].key })
	return out
}

func abs(x int) int {
	if x < 0 {
		return -x
	}
	return x
}

func render(es []entry) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/trigramgen; DO NOT EDIT.\n\npackage app\n\n")
	b.WriteString("// trigramTable holds trained trigram evidence, sorted by key. Each word is\n")
	b.WriteString("// (a<<14|b<<7|c)<<8 | (score-lo) for the ASCII bytes a,b,c: positive scores\n")
	b.WriteString("// mean benign identifier text, negative scores mean random secrets. Empty\n")
	b.WriteString("// means the borderline trigram escalation is off.\n")
	b.WriteString("var trigramTable = []uint32{\n")
	for _, e := range es {
		_, _ = fmt.Fprintf(&b, "\t0x%08x,\n", pack(e.key, e.score))
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

func main() {
	if err := run(os.Args[1:], os.Stdout, os.Stderr); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return
		}
		_, _ = fmt.Fprintln(os.Stderr, "trigramgen:", err)
		os.Exit(1)
	}
}

// run is main without the process: it parses args, trains and writes the table.
func run(args []string, stdout, stderr io.Writer) error {
	fs := flag.NewFlagSet("trigramgen", flag.ContinueOnError)
	fs.SetOutput(stderr)
	benignArg := fs.String("benign", "", "comma-separated files or directories of real benign text (code, docs)")
	secretsFile := fs.String("secrets", "", "optional file with one real secret per line")
	synth := fs.Int("synthetic", 0, "number of synthetic secrets (hex, base62, base64url; no eyJ) to add")
	synthBenign := fs.Int("synthetic-benign", 0, "number of synthetic benign identifiers to add")
	holdoutMod := fs.Int("holdout-mod", 0, "if > 0, files whose path hash % N == 0 are kept out of training (they are the holdout)")
	out := fs.String("out", "trigram_trained.go", "output file")
	if err := fs.Parse(args); err != nil {
		return err
	}

	benign, secret := newCounts(), newCounts()
	nb, ns := 0, 0
	for _, root := range strings.Split(*benignArg, ",") {
		if root = strings.TrimSpace(root); root == "" {
			continue
		}
		if err := corpus.Walk(root, *holdoutMod, false, func(text string) { nb += addText(benign, text) }); err != nil {
			return fmt.Errorf("walking -benign: %w", err)
		}
	}
	for _, s := range corpus.Benign(*synthBenign, corpus.SeedTrain) {
		addToken(benign, s)
		nb++
	}
	if *secretsFile != "" {
		f, err := cliio.Open(*secretsFile)
		if err != nil {
			return fmt.Errorf("opening -secrets: %w", err)
		}
		sc := bufio.NewScanner(f)
		sc.Buffer(make([]byte, 1<<20), 1<<20)
		for sc.Scan() {
			if t := strings.TrimSpace(sc.Text()); len(t) >= corpus.MinTokenLen {
				addToken(secret, t)
				ns++
			}
		}
		err = sc.Err()
		_ = f.Close()
		if err != nil {
			return fmt.Errorf("reading -secrets: %w", err)
		}
	}
	for _, s := range corpus.Secrets(*synth, corpus.SeedTrain) {
		addToken(secret, s)
		ns++
	}

	es := train(benign, secret)
	if len(es) == 0 {
		return fmt.Errorf("no table (benign tokens %d, secret tokens %d); need both and enough evidence", nb, ns)
	}
	if size := len(es) * 4; len(es) > maxEntries || size > maxBytes {
		return fmt.Errorf("table too large: %d entries, %d bytes", len(es), size)
	}
	src, err := render(es)
	if err != nil {
		return fmt.Errorf("rendering: %w", err)
	}
	if err := os.WriteFile(*out, src, 0o600); err != nil {
		return fmt.Errorf("writing: %w", err)
	}
	_, _ = fmt.Fprintf(stdout, "trigramgen: %d entries, %d bytes (%.1f KiB, budget %d entries / %d KiB) from %d benign and %d secret tokens -> %s\n",
		len(es), len(es)*4, float64(len(es)*4)/1024, maxEntries, maxBytes>>10, nb, ns, *out)
	return nil
}
