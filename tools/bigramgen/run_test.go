const benignSrc = "func getCustomerProfile() { handleRequest(the_other_thing); internationalization = parseConfigValue }\n"

// writeFile creates dir/name with data and returns its path.
func writeFile(t *testing.T, dir, name, data string) string {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.WriteFile(p, []byte(data), 0o600); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestRunWritesTable(t *testing.T) {
	dir := t.TempDir()
	benignDir := filepath.Join(dir, "src")
	if err := os.Mkdir(benignDir, 0o700); err != nil {
		t.Fatal(err)
	}
	for _, n := range []string{"a.go", "b.go", "c.go", "d.go"} {
		writeFile(t, benignDir, n, strings.Repeat(benignSrc, 40))
	}
	secrets := writeFile(t, dir, "secrets.txt", "abc\n  \n"+strings.Repeat("Zk3qP9xLw0aVb7TnRu1sYd5H\n", 20))
	out := filepath.Join(dir, "out.go")

	var stdout, stderr bytes.Buffer
	args := []string{
		"-benign", " " + benignDir + " ,, ",
		"-secrets", secrets,
		"-synthetic", "2000", "-synthetic-benign", "2000",
		"-holdout-mod", "1000000007", "-out", out,
	}
	if err := run(args, &stdout, &stderr); err != nil {
		t.Fatalf("run: %v\nstderr: %s", err, stderr.String())
	}
	if !strings.Contains(stdout.String(), "bigramgen: ") || !strings.Contains(stdout.String(), out) {
		t.Errorf("stdout = %q", stdout.String())
	}
	src, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(src), "Code generated by tools/bigramgen; DO NOT EDIT.") {
		t.Errorf("output is not the generated table:\n%.200s", src)
	}
}

func TestRunErrors(t *testing.T) {
	dir := t.TempDir()
	benignFile := writeFile(t, dir, "a.go", strings.Repeat(benignSrc, 40))
	hugeLine := writeFile(t, dir, "huge.txt", strings.Repeat("a", 2<<20)+"\n")
	cases := []struct {
		name string
		args []string
		want string
	}{
		{"bad flag", []string{"-nope"}, "not defined"},
		{"bad flag value", []string{"-synthetic", "x"}, "invalid value"},
		{"missing benign dir", []string{"-benign", filepath.Join(dir, "missing")}, "missing"},
		{"missing secrets file", []string{"-benign", benignFile, "-secrets", filepath.Join(dir, "none.txt")}, "none.txt"},
		{"unreadable secrets line", []string{"-benign", benignFile, "-secrets", hugeLine}, "-secrets"},
		{"no benign and no secrets", nil, "no table"},
		{"no secret class", []string{"-benign", benignFile}, "no table"},
		{"unwritable out", []string{"-benign", benignFile, "-synthetic", "2000", "-synthetic-benign", "2000", "-out", filepath.Join(dir, "no", "such", "out.go")}, "out.go"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			err := run(tc.args, &stdout, &stderr)
			if err == nil {
				t.Fatalf("want error containing %q, got nil", tc.want)
			}
			if !strings.Contains(err.Error()+stderr.String(), tc.want) {
				t.Errorf("error %q / stderr %q lack %q", err, stderr.String(), tc.want)
			}
			if stdout.Len() != 0 {
				t.Errorf("stdout should be empty on error, got %q", stdout.String())
			}
		})
	}
}

func TestRunHelp(t *testing.T) {
	var stdout, stderr bytes.Buffer
	err := run([]string{"-h"}, &stdout, &stderr)
	if !errors.Is(err, flag.ErrHelp) {
		t.Fatalf("err = %v, want flag.ErrHelp", err)
	}
	if !strings.Contains(stderr.String(), "-holdout-mod") {
		t.Errorf("usage not written to stderr: %q", stderr.String())
	}
}

func rcovNeedsChmod(t *testing.T) {
	t.Helper()
	if runtime.GOOS == "windows" || os.Geteuid() == 0 {
		t.Skip("needs a non-root POSIX user (permission bits)")
	}
}

// rcovLock sets mode on path and restores 0o700 at cleanup so TempDir can be removed.
func rcovLock(t *testing.T, path string, mode os.FileMode) {
	t.Helper()
	if err := os.Chmod(path, mode); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chmod(path, 0o700) })
}

func TestRcovRunUnreadableBenignInputs(t *testing.T) {
	rcovNeedsChmod(t)
	dir := t.TempDir()
	if err := os.Mkdir(filepath.Join(dir, "locked"), 0o700); err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(dir, "locked"), "a.go", benignSrc)
	rcovLock(t, filepath.Join(dir, "locked"), 0)
	file := writeFile(t, dir, "b.go", benignSrc)
	rcovLock(t, file, 0)

	for name, benign := range map[string]string{"unreadable folder": dir, "unreadable file": file} {
		var stdout, stderr bytes.Buffer
		err := run([]string{"-benign", benign, "-out", filepath.Join(dir, "o.go")}, &stdout, &stderr)
		if err == nil || !strings.Contains(err.Error(), "permission denied") {
			t.Errorf("%s: err = %v, want permission denied", name, err)
		}
		if stdout.Len() != 0 {
			t.Errorf("%s: stdout should be empty, got %q", name, stdout.String())
		}
	}
}

